def get_dist_info():
    """Rank/world-size from the environment, for the data pipeline's sharding.

    Returns `(is_multiprocess, rank, local_rank, world_size)`. There is no process
    group to initialize any more; this only reads env vars so that `dataset.py` and
    `tasks/` can shard work if they happen to be launched multi-process.
    """
    keys = ("RANK", "LOCAL_RANK", "WORLD_SIZE")
    if all(k in os.environ for k in keys):
        return True, int(os.environ["RANK"]), int(os.environ["LOCAL_RANK"]), int(os.environ["WORLD_SIZE"])
    return False, 0, 0, 1
